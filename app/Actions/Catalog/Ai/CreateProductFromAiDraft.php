<?php

namespace App\Actions\Catalog\Ai;

use App\Actions\Catalog\SaveProduct;
use App\Enums\ActivityType;
use App\Enums\AiDraftStatus;
use App\Enums\ProductType;
use App\Models\Activity;
use App\Models\AiProductDraft;
use App\Models\Product;
use App\Models\User;
use App\Support\Catalog\ProductAttributeResolver;
use App\Support\Catalog\ProductFormData;
use App\Support\Catalog\ResolvedAttribute;
use App\Support\Content\AiProduct\ProductAiDraft;
use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Contracts\Cache\LockTimeoutException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\Validator;
use Illuminate\Validation\ValidationException;

/**
 * Create a product from an AI wizard draft (plan 32 §6, plan change 5,
 * PW-14, PW-20, PW-30). Everything from the wizard is re-validated first
 * (AiDraftProposal + the product form rules), then:
 *
 *  1. one transaction: lock the draft (an applying / applied draft returns its
 *     product: idempotent), SaveProduct with is_active = false,
 *     is_featured = false and no badge (never from AI keys), draft → applying
 *     with product_id;
 *  2. the images outside that transaction (ApplyAiDraftImages, resumable);
 *  3. draft → applied, Activity "ai_create" with field keys and counts only
 *     (PW-19), the draft's clean/ folder deleted.
 *
 * Price, slug, publish state and badge never come from the model: the price
 * is the one the user typed in step 1 (read from the draft row), the slug is
 * generated by SaveProduct.
 * One apply per draft at a time (cache lock).
 */
class CreateProductFromAiDraft
{
    public function __construct(
        private readonly SaveProduct $save,
        private readonly AiDraftProposal $proposal,
        private readonly ApplyAiDraftImages $images,
        private readonly PrepareAiDraftImages $files,
        private readonly ProductAttributeResolver $resolver,
    ) {}

    /**
     * @throws AuthorizationException
     * @throws ValidationException
     */
    public function handle(User $user, AiProductDraft $draft, ProductAiDraft $data): Product
    {
        $type = ProductType::tryFrom((string) ($draft->input['info']['type'] ?? ''));

        if ($draft->isImprove() || $draft->user_id !== $user->id || $type === null || ! AiWizardGate::allowsCreate($user, $type)) {
            throw new AuthorizationException;
        }

        try {
            return AiDraftLock::run($draft->id, fn (): Product => $this->run($user, $draft, $data));
        } catch (LockTimeoutException) {
            throw ValidationException::withMessages(['draft' => __('admin.ai_wizard.errors.busy')]);
        }
    }

    private function run(User $user, AiProductDraft $draft, ProductAiDraft $data): Product
    {
        $draft->refresh();
        // An interrupted apply (F3): the product exists, only the images are left; its SKU is taken now.
        $resuming = $draft->product_id !== null && in_array($draft->status, [AiDraftStatus::Applying, AiDraftStatus::Applied], true);
        $texts = $this->proposal->texts($data->texts, ProductAiDraft::TEXT_FIELDS);
        $alts = $this->proposal->alts($data->alts, count((array) ($draft->input['images'] ?? [])));
        // Step 1 as saved (and validated) in the draft row, never the client's copy.
        $info = AiDraftProposal::info((array) ($draft->input['info'] ?? []));
        $categoryId = (int) $info['category_id'] ?: null;
        $specs = $this->proposal->specs($data->specs, AiDraftProposal::acceptedSpecIds($data), $categoryId);

        $rows = array_map(
            fn (ResolvedAttribute $row): array => ProductFormData::blankRow($row->attribute->id, $row->isExtra()),
            $this->resolver->categoryAttributes($categoryId),
        );

        $state = [
            ...$this->blankState(),
            ...$info,
            'specs' => AiDraftProposal::overlaySpecs($rows, $specs, []),
        ];

        foreach (ProductAiDraft::TEXT_FIELDS as $field) {
            foreach (config('app.supported_locales') as $locale) {
                $state[$field][$locale] = $texts[$field][$locale] ?? '';
            }
        }

        if (! $resuming) {
            Validator::make($state, ProductFormData::rules())->validate();
        }

        $product = DB::transaction(function () use ($user, $draft, $state): Product {
            $locked = AiProductDraft::query()->whereKey($draft->id)->where('user_id', $user->id)->lockForUpdate()->firstOrFail();

            // A resumed apply never writes to a product deleted meanwhile (N7).
            if ($locked->product_id !== null && in_array($locked->status, [AiDraftStatus::Applying, AiDraftStatus::Applied], true)) {
                $resumed = Product::query()->find($locked->product_id)
                    ?? throw ValidationException::withMessages(['draft' => __('admin.ai_wizard.errors.state')]);

                // Resuming writes to the product: the user must still be allowed to edit it (L3).
                if (! Gate::forUser($user)->allows('update', $resumed)) {
                    throw new AuthorizationException;
                }

                return $resumed;
            }

            // A product was already created by an apply that was then marked failed (prune): never a second one.
            if ($locked->product_id !== null) {
                throw ValidationException::withMessages(['draft' => __('admin.ai_wizard.errors.state')]);
            }

            if (! in_array($locked->status, [AiDraftStatus::Ready, AiDraftStatus::Truncated], true)) {
                throw ValidationException::withMessages(['draft' => __('admin.ai_wizard.errors.state')]);
            }

            $product = $this->save->handle(null, ProductFormData::saveData($state), ProductFormData::specInput($state['specs']));

            AiDraftState::move($locked->id, [AiDraftStatus::Ready, AiDraftStatus::Truncated], AiDraftStatus::Applying, [
                'product_id' => $product->id,
                'apply_state' => ['done' => [], 'counts' => []],
            ]);

            return $product;
        });

        $draft->refresh();

        if ($draft->status === AiDraftStatus::Applied) {
            return $product;
        }

        $counts = $this->images->handle($draft, $product, $data, $alts);

        if (AiDraftState::move($draft->id, [AiDraftStatus::Applying], AiDraftStatus::Applied, ['applied_at' => now()])) {
            $fields = array_values(array_filter(ProductAiDraft::TEXT_FIELDS, fn (string $field): bool => isset($texts[$field])));

            Activity::query()->create([
                'subject_type' => $product->getMorphClass(),
                'subject_id' => $product->id,
                'user_id' => $user->id,
                'type' => ActivityType::AiCreate,
                'body' => AiDraftActivity::body($fields, count($specs), $counts),
                'meta' => ['draft_id' => $draft->id, 'fields' => $fields, 'specs' => count($specs), 'images' => $counts],
            ]);

            $this->files->deleteClean($draft->uuid);
            $this->files->deleteVision($draft->uuid);
            $this->files->deletePreview($draft->uuid);
        }

        return $product->fresh() ?? $product;
    }

    /**
     * The product form's defaults (a new product: draft, not featured, no badge).
     *
     * @return array<string, mixed>
     */
    private function blankState(): array
    {
        $empty = array_fill_keys(config('app.supported_locales'), '');

        return [
            'name' => $empty,
            'short_description' => $empty,
            'description' => $empty,
            'meta_title' => $empty,
            'meta_description' => $empty,
            'slug' => '',
            'price_dealer' => '',
            'price_wholesale' => '',
            'pricing_unit' => 'unit',
            'roll_type_ids' => [],
            'unit' => 'piece',
            'min_qty' => '1',
            'stock_status' => 'in_stock',
            'ikpu_code' => '',
            'package_code' => '',
            'warranty_months' => '',
            'badge' => '',
            'is_active' => false,
            'is_featured' => false,
        ];
    }
}
